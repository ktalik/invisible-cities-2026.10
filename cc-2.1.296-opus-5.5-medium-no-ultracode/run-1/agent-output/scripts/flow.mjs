import { chromium } from 'playwright-core';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--use-angle=vulkan', '--enable-gpu', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const logs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto('http://localhost:5199/');
await page.waitForFunction(() => window.__ready === true, null, { timeout: 180000 });
await page.click('#start-journey');
await page.waitForTimeout(3500);
await page.screenshot({ path: `${out}/f1.png` });
await page.click('.il-go');
await page.waitForTimeout(5000);
await page.screenshot({ path: `${out}/f2.png` });
console.log('hash after first city', await page.evaluate(() => location.hash));
await page.keyboard.press('ArrowRight');
await page.waitForTimeout(4000);
console.log('hash after right', await page.evaluate(() => location.hash));
await page.click('#btn-index');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/f3.png` });
await page.click('#legend button:nth-child(6)');
await page.waitForTimeout(500);
await page.keyboard.press('Escape');
await page.waitForTimeout(4000);
await page.screenshot({ path: `${out}/f4.png` });
await page.keyboard.press('2');
await page.waitForTimeout(1300);
await page.screenshot({ path: `${out}/f5.png` });
for (const l of [...new Set(logs)].filter((l) => !l.includes('deprecated') && !l.includes('PCFSoft') && !l.includes('GPU stall') && !l.includes('non-indexed'))) console.log(l);
await browser.close();
